"""Build-time backend modules. No discovery or loader runs during inference.

backend.json describes source files and supported build platforms. This helper
validates it, writes a small Makefile fragment and an X-macro registry, or copies
a user-selected source module into an installation. It never imports module code.
"""
from pathlib import Path
import argparse
import json
import os
import re
import shutil
import sys
import tempfile

API = 1
MAX_MODULES = 10                 # Six built-in/legacy slots + ten modules <= 16.
RESERVED = {"auto", "avx2", "neon", "metal", "metal_ssd"}
NAME = re.compile(r"[a-z][a-z0-9_]{0,14}\Z")
PATH = re.compile(r"[A-Za-z0-9_./-]+\Z")
LINK_FLAG = re.compile(r"[-+A-Za-z0-9_./:=,]+\Z")
SYSTEMS = {"Darwin", "Linux"}
ARCHES = {"arm64", "aarch64", "x86_64"}


def valid_name(name):
    return isinstance(name, str) and NAME.fullmatch(name) and name not in RESERVED and not name.startswith("ref")


def files(directory):
    result = []
    for path in sorted(directory.rglob("*")):
        relative = path.relative_to(directory)
        if "__pycache__" in relative.parts or path.name == ".DS_Store":
            continue
        if path.is_symlink():
            raise ValueError(f"Module contains a symlink: {relative}")
        if path.is_file():
            if not PATH.fullmatch(relative.as_posix()) or any(p.startswith('.') for p in relative.parts):
                raise ValueError(f"Unsupported module filename: {relative}")
            result.append(relative)
    return result


def read_module(directory):
    directory = Path(directory)
    if directory.is_symlink():
        raise ValueError("Choose the source module directory, not a symlink")
    entries = files(directory)
    data = json.loads((directory / "backend.json").read_text())
    allowed = {"api", "name", "sources", "systems", "architectures", "ldlibs"}
    if not isinstance(data, dict) or set(data) - allowed:
        raise ValueError("backend.json has unknown fields")
    if type(data.get("api")) is not int or data["api"] != API:
        raise ValueError(f"backend.json must use api {API}")
    if not valid_name(data.get("name")):
        raise ValueError("Use a unique lowercase name: 1–15 letters/digits/underscores, starting with a letter; built-in/ref names are reserved")
    sources = data.get("sources")
    if not isinstance(sources, list) or not sources or not all(isinstance(s, str) for s in sources):
        raise ValueError("sources must list the module's C/Objective-C source files")
    if len(set(sources)) != len(sources):
        raise ValueError("Duplicate module source")
    for source in sources:
        p = Path(source)
        if p.is_absolute() or ".." in p.parts or not PATH.fullmatch(source) or p.suffix not in {".c", ".m"} or p not in entries:
            raise ValueError(f"Invalid or missing module source: {source}")
    for field, choices in (("systems", SYSTEMS), ("architectures", ARCHES)):
        value = data.setdefault(field, sorted(choices))
        if not isinstance(value, list) or not value or not all(isinstance(v, str) and v in choices for v in value):
            raise ValueError(f"{field} must be a nonempty list drawn from {sorted(choices)}")
    flags = data.setdefault("ldlibs", [])
    if not isinstance(flags, list) or not all(isinstance(v, str) and LINK_FLAG.fullmatch(v) for v in flags):
        raise ValueError("ldlibs must be separate linker arguments without spaces or shell/Make syntax")
    return data, entries


def write_if_changed(path, text):
    if path.exists() and path.read_text() == text:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(mode="w", dir=path.parent, delete=False) as stream:
        stream.write(text)
        temporary = stream.name
    os.replace(temporary, path)


def configure(root, system, arch):
    modules = []; sources = []; inputs = []; libraries = []
    for manifest in sorted((root / "backends/modules").glob("*/backend.json")):
        if manifest.parent.name.startswith('.'):
            continue
        data, entries = read_module(manifest.parent)
        if data['name'] != manifest.parent.name:
            raise ValueError(f"Module folder must be named {data['name']}")
        if system not in data['systems'] or arch not in data['architectures']:
            continue
        modules.append(data['name'])
        relative = manifest.parent.relative_to(root)
        sources.extend(str(relative / s) for s in data['sources'])
        inputs.extend(str(relative / s) for s in entries)
        libraries.extend(data['ldlibs'])
    if len(modules) > MAX_MODULES:
        raise ValueError(f"At most {MAX_MODULES} custom modules can be compiled together")
    out = root / 'build/backend-modules'
    header = '/* Generated by tools/backend-module.py; edit backend.json instead. */\n'
    header += ''.join(f'FR_BACKEND_MODULE({name})\n' for name in modules)
    fragment = '# Generated module inputs. Registration is static, just like built-ins.\n'
    for name, values in [('FR_MODULE_SOURCES', sources), ('FR_MODULE_INPUTS', inputs),
                         ('FR_MODULE_LDLIBS', libraries), ('FR_MODULE_NAMES', modules)]:
        fragment += f'{name} := {" ".join(values)}\n'
    write_if_changed(out / 'registry.h', header)
    write_if_changed(out / 'modules.mk', fragment)


def new_module(name, destination):
    if not valid_name(name):
        raise ValueError('Invalid or reserved module name')
    if destination.exists():
        raise ValueError(f'Refusing to replace {destination}')
    template = Path(__file__).resolve().parent.parent / 'backends/user-template.c'
    source = template.read_text().replace('fr_user', f'fr_module_{name}').replace('"mine"', f'"{name}"')
    source = source[source.index('#include'):]
    source = source.replace('#include "../src/', '#include "')
    source = f'/* {name}: scalar starting point. See docs/BACKEND_MODULES.md before optimizing. */\n' + source
    destination.mkdir(parents=True)
    (destination/'backend.c').write_text(source)
    (destination/'backend.json').write_text(json.dumps({'api': API, 'name': name, 'sources': ['backend.c'],
        'systems': sorted(SYSTEMS), 'architectures': sorted(ARCHES)}, indent=2)+'\n')
    (destination/'README.md').write_text(f'# {name}\n\nDescribe the hardware, dependencies, numerical checks and timings here.\n'
        'The initial implementation is portable scalar code, not an optimized kernel.\n')


def copy_module(source, parent, replace):
    data, entries = read_module(source)
    target = parent / data['name']
    if target.exists():
        old, old_entries = read_module(target)
        if old_entries == entries and all((source/p).read_bytes() == (target/p).read_bytes() for p in entries):
            return data['name']
        if not replace:
            raise ValueError(f'Module {data["name"]} already exists; use a different name or explicitly replace your local module')
    parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix='.module-', dir=parent) as temporary:
        staged = Path(temporary) / data['name']; staged.mkdir()
        for relative in entries:
            dest = staged / relative; dest.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(source / relative, dest)
        previous = parent / ('.' + data['name'] + '.previous')
        if target.exists():
            if previous.exists():
                shutil.rmtree(previous)
            target.rename(previous)
        try:
            staged.rename(target)
        except OSError:
            if previous.exists() and not target.exists():
                previous.rename(target)
            raise
    return data['name']


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest='command', required=True)
    new = commands.add_parser('new'); new.add_argument('name'); new.add_argument('destination', nargs='?', type=Path)
    validate = commands.add_parser('validate'); validate.add_argument('directory', type=Path)
    build = commands.add_parser('configure'); build.add_argument('--root', type=Path, default=Path('.'))
    build.add_argument('--system', required=True); build.add_argument('--arch', required=True)
    copy = commands.add_parser('copy'); copy.add_argument('source', type=Path); copy.add_argument('parent', type=Path)
    copy.add_argument('--replace', action='store_true')
    args = parser.parse_args()
    if args.command == 'new':
        destination = args.destination or Path('backends/modules') / args.name
        new_module(args.name, destination); print(destination)
    elif args.command == 'validate':
        print(read_module(args.directory)[0]['name'])
    elif args.command == 'configure':
        configure(args.root, args.system, args.arch)
    else:
        print(copy_module(args.source, args.parent, args.replace))


if __name__ == '__main__':
    try:
        main()
    except (OSError, ValueError) as error:
        sys.exit(f'Backend module: {error}')
